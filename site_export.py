"""Everything the research app displays, computed here in Python (the app only formats and plots these values).

Two modes:
  local   full research view from your licensed files: prices, spread z-score, fills, holdings, trade replays, case facts.
  public  built from an allow-list, never by deleting fields from the local view. Tier "aggregate" (default) carries only
          period-level statistics, scenario aggregates, sourced case narratives, documentation and a synthetic replay. Tier "derived"
          adds the daily strategy equity series, trade outcomes without prices or share counts, and computed case facts.
          Neither tier contains security prices, spread values, fills or holdings. See docs/DATA_PERMISSIONS.md.
The synthetic replay is generated by data_io.synthetic_market and run through the same signal and engine code. It is labelled as
synthetic everywhere, uses session numbers instead of calendar dates, and is never combined with historical performance."""
