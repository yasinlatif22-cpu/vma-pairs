def _d(x):
    return None if pd.isna(x) else pd.Timestamp(x).strftime("%Y-%m-%d")


def _f(x, nd=6):
    return None if x is None or (isinstance(x, float) and not np.isfinite(x)) or pd.isna(x) else round(float(x), nd)


def code_commit():
    try:
        h = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True).stdout.strip()
        return h + ("+uncommitted" if dirty else "")
    except Exception:
        return "unknown"


# ---------------------------------------------------------------- loading
def load(res="results_rerun"):
    o, c, d = load_market("data/processed/market.csv", [DEFAULT.y, DEFAULT.x])
    runs = {}
    for p in PERIODS:
        base = Path(res) / f"{p}_none_open_next"
        runs[p] = dict(daily=pd.read_csv(base / "daily.csv", parse_dates=["date"]).set_index("date"),
                       trades=pd.read_csv(base / "trades.csv", parse_dates=["signal_date", "entry_date", "exit_signal_date", "exit_date"]),
                       windows=pd.read_csv(base / "windows.csv", parse_dates=["start", "end"]))
    close_fill = {p: pd.read_csv(Path(res) / f"{p}_none_close_next" / "trades.csv", parse_dates=["signal_date"]) for p in ("dev", "val")}
    rf, rf_label = load_rf()
    ff = pd.read_csv("data/raw/rf.csv", parse_dates=["date"]).set_index("date")
    mkt = (ff.mktrf + ff.rf).rename("mkt")
    earn = pd.read_csv("data/raw/earnings.csv", parse_dates=["datadate", "rdq"])
    z = {}
    for p, (a, b) in PERIODS.items():
        s, _ = build_signals(c.loc[:b], DEFAULT, c.index.searchsorted(pd.Timestamp(a)))
        z[p] = s.loc[a:b]
    scen = pd.read_csv(Path(res) / "scenarios.csv") if (Path(res) / "scenarios.csv").exists() else None
    return dict(o=o, c=c, d=d, runs=runs, close_fill=close_fill, rf=rf, rf_label=rf_label, mkt=mkt, earn=earn, sig=z, scen=scen)


# ---------------------------------------------------------------- statistics (aggregates)
def sample_stats(L):
    out = {}
    for name, ps in SAMPLES.items():
        r = pd.concat([L["runs"][p]["daily"].ret for p in ps])
        pf = perf(r)
        lo, hi = pooled_stats.boot_ci(r)
        ex = {}
        for sc in ("S0", "S1", "S2"):
            e = pd.concat([(lambda a: a.ret - a.rf)(account(L["runs"][p]["daily"], L["rf"], sc)) for p in ps])
            ex[sc] = dict(ann=_f(e.mean() * 252), sharpe=_f(e.mean() / e.std() * np.sqrt(252)))
        tb = [tbill(L["runs"][p]["daily"].index, L["rf"]) for p in ps]
        tb_cagr = float(np.prod([t.iloc[-1] / 1e6 for t in tb]) ** (252 / len(r)) - 1)
        trades = pd.concat([L["runs"][p]["trades"] for p in ps])
        out[name] = dict(periods=ps, start=_d(r.index[0]), end=_d(r.index[-1]), days=len(r), trades=len(trades),
                         mean_ann_ret=_f(pf["mean_ann_ret"]), cagr=_f(pf["cagr"]), vol=_f(pf["ann_vol"]), sharpe=_f(pf["sharpe"]),
                         nw_t=_f(pooled_stats.nw_t(r)), sharpe_ci=[_f(lo), _f(hi)],
                         max_dd=_f(min(perf(L["runs"][p]["daily"].ret)["max_dd"] for p in ps)),
                         utilization=_f(pd.concat([L["runs"][p]["daily"].in_trade for p in ps]).mean()),
                         net_pnl=_f(trades.net_pnl.sum(), 2), win_rate=_f((trades.net_pnl > 0).mean()), excess=ex, tbill_cagr=_f(tb_cagr))
    return out


def execution_stats(L):
    out = {}
    for p in ("dev", "val"):
        o = L["runs"][p]["trades"].set_index("signal_date").gross_pnl
        c = L["close_fill"][p].set_index("signal_date").gross_pnl
        diff = (o - c)
        m = diff[diff.index.isin(pd.to_datetime(MARCH_2020))]
        rest = diff[~diff.index.isin(pd.to_datetime(MARCH_2020))]
        cl = L["scen"]
        sh_close = None
        if cl is not None:
            q = cl[(cl["sample"] == p) & (cl.cost_bps == 5) & (cl.borrow_bps == 30) & (cl.fill_lag == 1) & (cl.fill == "close_next")]
            sh_close = _f(q.sharpe.iloc[0]) if len(q) else None
        out[p] = dict(trades=len(diff), gross_open=_f(o.sum(), 2), gross_close=_f(c.sum(), 2), diff=_f(diff.sum(), 2),
                      share_open_better=_f((diff > 0).mean()), march2020=_f(m.sum(), 2) if p == "val" else None,
                      rest=_f(rest.sum(), 2) if p == "val" else None, rest_n=int(len(rest)) if p == "val" else None,
                      sharpe_open=_f(perf(L["runs"][p]["daily"].ret)["sharpe"]), sharpe_close=sh_close)
    return out


def concentration_stats(L):
    out = {}
    for name, ps in (("dev", ["dev"]), ("val", ["val"]), ("holdout", ["holdout"]), ("all", ["dev", "val", "holdout"])):
        t = pd.concat([L["runs"][p]["trades"] for p in ps]).net_pnl.sort_values(ascending=False)
        wins = t[t > 0].sum()
        out[name] = dict(trades=len(t), net=_f(t.sum(), 2), top1_share_of_wins=_f(t.iloc[0] / wins), top3_share_of_wins=_f(t.iloc[:3].sum() / wins),
                         net_excl_top3=_f(t.iloc[3:].sum(), 2))
    return out


def earnings_stats(L):
    cal = L["c"].index
    rel = earnings_analysis.release_sessions(L["earn"].rdq, cal)
    al = pd.concat([earnings_analysis.classify(L["runs"][p]["trades"], cal, rel).assign(period=p) for p in PERIODS])
    out = {}
    for tm in earnings_analysis.TIMINGS:
        a, b = al[al[f"exp_{tm}"]].pnl_pct.values, al[~al[f"exp_{tm}"]].pnl_pct.values
        lo, hi = earnings_analysis.boot_diff(a, b)
        out[tm] = dict(n_exposed=len(a), n_not=len(b), mean_exposed=_f(a.mean()), mean_not=_f(b.mean()), diff=_f(a.mean() - b.mean()), ci=[_f(lo), _f(hi)])
    return out


def scenario_records(L):
    s = L["scen"]
    if s is None:
        return None
    keep = ["sample", "cost_bps", "borrow_bps", "fill_lag", "fill", "timing", "baseline", "trades", "net_pnl", "mean_ann_ret", "cagr", "ann_vol",
            "sharpe", "max_dd", "utilization", "costs", "borrow_paid", "excess_sharpe_S0", "excess_sharpe_S1", "excess_sharpe_S2",
            "excess_ann_S0", "excess_ann_S1", "excess_ann_S2", "cagr_S0", "cagr_S1", "cagr_S2"]
    return [{k: (_f(v) if isinstance(v, (float, np.floating)) else (bool(v) if isinstance(v, (bool, np.bool_)) else v)) for k, v in r.items()}
            for r in s[keep].to_dict("records")]


# ---------------------------------------------------------------- trade-level (local / derived)
def trade_table(L):
    rows = []
    for p in PERIODS:
        R = L["runs"][p]
        lg = trade_legs.legs(R["trades"], R["daily"], {"close": L["c"], "div": L["d"]}, L["mkt"])
        for t, g in zip(R["trades"].itertuples(), lg.itertuples()):
            w = R["windows"][(R["windows"].start <= t.signal_date) & (R["windows"].end >= t.signal_date)].iloc[0]
            rows.append(dict(id=f"{_d(t.signal_date)}", period=p, side=int(t.side), signal_date=_d(t.signal_date), entry_date=_d(t.entry_date),
                             exit_signal_date=_d(t.exit_signal_date), exit_date=_d(t.exit_date), exit_reason=t.exit_reason,
                             hold_sessions=int(t.hold_sessions), hold_calendar_days=int(t.hold_calendar_days), beta=_f(t.beta),
                             half_life=_f(w.half_life), eg_p=_f(w.eg_p), max_hold=int(w.max_hold),
                             z_signal=_f(L["sig"][p].z.get(t.signal_date)),
                             qty_v=_f(t.qty_y), qty_ma=_f(t.qty_x), entry_px_v=_f(t.entry_px_y), entry_px_ma=_f(t.entry_px_x),
                             exit_px_v=_f(t.exit_px_y), exit_px_ma=_f(t.exit_px_x),
                             gross_pnl=_f(t.gross_pnl, 2), dividends=_f(t.dividends, 2), costs=_f(t.costs, 2), borrow=_f(t.borrow, 2),
                             net_pnl=_f(t.net_pnl, 2), equity_basis=_f(t.equity_basis, 2), pnl_pct=_f(t.net_pnl / t.equity_basis),
                             v_price_pnl=_f(g.V_price_pnl, 2), ma_price_pnl=_f(g.MA_price_pnl, 2), v_div=_f(g.V_dividends, 2), ma_div=_f(g.MA_dividends, 2),
                             v_costs=_f(g.V_costs, 2), ma_costs=_f(g.MA_costs, 2), v_beta=_f(g.V_beta), ma_beta=_f(g.MA_beta),
                             v_market_est=_f(g.V_market_est, 2), ma_market_est=_f(g.MA_market_est, 2), market_return=_f(g.market_return)))
    return rows


def replay_rows(t, L, before=15, after=5):
    """Session-by-session ledger for one trade from the recorded fills and share counts. Must end at the trade's net P&L."""
    c, o, dv = L["c"], L["o"], L["d"]
    cal = c.index
    R = L["runs"][t["period"]]
    daily, z = R["daily"], L["sig"][t["period"]].z
    s_i, e_i, x_i = cal.get_loc(pd.Timestamp(t["signal_date"])), cal.get_loc(pd.Timestamp(t["entry_date"])), cal.get_loc(pd.Timestamp(t["exit_date"]))
    xs_i = cal.get_loc(pd.Timestamp(t["exit_signal_date"]))
    q = {"V": t["qty_v"], "MA": t["qty_ma"]}
    p0 = {"V": t["entry_px_v"], "MA": t["entry_px_ma"]}
    p1 = {"V": t["exit_px_v"], "MA": t["exit_px_ma"]}
    bps = DEFAULT.cost_bps / 1e4
    cost_in = sum(bps * abs(q[k]) * p0[k] for k in q)
    cost_out = sum(bps * abs(q[k]) * p1[k] for k in q)
    rows, div_cum, bor_cum = [], 0.0, 0.0
    lo, hi = max(0, s_i - before), min(len(cal) - 1, x_i + after)
    for k in range(lo, hi + 1):
        d = cal[k]
        phase = ("before" if k < s_i else "signal" if k == s_i else "pending" if k < e_i else "entry" if k == e_i
                 else "exit_signal" if k == xs_i and k < x_i else "hold" if k < x_i else "exit" if k == x_i else "after")
        leg = {}
        for name in ("V", "MA"):
            if k < e_i:
                leg[name] = 0.0
            elif k < x_i or (k == x_i and False):
                leg[name] = q[name] * (c.at[d, name] - p0[name])
            else:
                leg[name] = q[name] * (p1[name] - p0[name])
            if e_i < k <= x_i:
                div_cum += q[name] * dv.at[d, name]
        if e_i <= k < x_i:
            bor_cum += float(daily.borrow.get(d, 0.0))
        costs = (cost_in if k >= e_i else 0.0) + (cost_out if k >= x_i else 0.0)
        net = leg["V"] + leg["MA"] + div_cum - costs - bor_cum
        rows.append(dict(i=k - s_i, date=_d(d), phase=phase, open_v=_f(o.at[d, "V"], 4), open_ma=_f(o.at[d, "MA"], 4),
                         close_v=_f(c.at[d, "V"], 4), close_ma=_f(c.at[d, "MA"], 4), z=_f(z.get(d)),
                         held=max(0, min(k, x_i) - e_i) if k >= e_i else 0, pnl_v=_f(leg["V"], 2), pnl_ma=_f(leg["MA"], 2),
                         div=_f(div_cum, 2), costs=_f(costs, 2), borrow=_f(bor_cum, 2), net=_f(net, 2),
                         mtm_vs_limit=_f((net + (cost_out if k >= x_i else 0.0)) / t["equity_basis"])))
    final = rows[x_i - lo]["net"]
    if abs(final - t["net_pnl"]) > 0.01:
        raise AssertionError(f"replay for {t['id']} ends at {final:,.2f}, trade net is {t['net_pnl']:,.2f}")
    return rows


def case_facts(L, trades):
    spec = json.loads(Path("docs/case_studies.json").read_text())
    e = L["earn"].dropna(subset=["rdq", "epsfxq", "ajexq", "saleq"])
    fq = {tk: g for tk, g in e.groupby("ticker")}
    c = L["c"]
    out = []
    for case in spec["cases"]:
        t = next(x for x in trades if x["signal_date"] == case["id"])
        sd = pd.Timestamp(case["id"])
        val = {tk: case_valuation.describe(fq[tk], c.at[sd, tk], sd) for tk in ("V", "MA")}
        prev = c.index[c.index.get_loc(sd) - 1]
        day = {tk: _f(c.at[sd, tk] / c.at[prev, tk] - 1) for tk in ("V", "MA")}
        facts = dict(model=dict(beta=t["beta"], half_life=t["half_life"], eg_p=t["eg_p"], max_hold=t["max_hold"], z_signal=t["z_signal"]),
                     signal_day=dict(v=day["V"], ma=day["MA"], market=_f(L["mkt"].get(sd))),
                     valuation=dict(label=spec["valuation_label"],
                                    v=dict(pe=_f(val["V"]["pe"]), growth=_f(val["V"]["sales_growth"]), margin=_f(val["V"]["op_margin"]), last_report=str(val["V"]["last_report"])),
                                    ma=dict(pe=_f(val["MA"]["pe"]), growth=_f(val["MA"]["sales_growth"]), margin=_f(val["MA"]["op_margin"]), last_report=str(val["MA"]["last_report"]))),
                     outcome=dict(exit_reason=t["exit_reason"], hold_sessions=t["hold_sessions"], hold_calendar_days=t["hold_calendar_days"], net_pnl=t["net_pnl"],
                                  pnl_pct=t["pnl_pct"], gross=t["gross_pnl"], dividends=t["dividends"], costs=t["costs"], borrow=t["borrow"],
                                  v_price_pnl=t["v_price_pnl"], ma_price_pnl=t["ma_price_pnl"], v_div=t["v_div"], ma_div=t["ma_div"],
                                  v_market_est=t["v_market_est"], ma_market_est=t["ma_market_est"], v_beta=t["v_beta"], ma_beta=t["ma_beta"],
                                  market_return=t["market_return"], exit_date=t["exit_date"]))
        if "adjusted_ttm_eps" in case:
            a = case["adjusted_ttm_eps"]
            facts["valuation"]["adjusted"] = dict(v_pe=_f(c.at[sd, "V"] / a["V"]), ma_pe=_f(c.at[sd, "MA"] / a["MA"]), note=a["note"])
        out.append(dict(case, facts=facts, side=t["side"]))
    return dict(selection_rule=spec["selection_rule"], valuation_label=spec["valuation_label"], valuation_limits=spec["valuation_limits"], cases=out)


def synthetic_demo():
    """Replays on a synthetic pair through the same code. Dates are replaced by session numbers."""
    long, mret = synthetic_market(seed=11, n=1100, beta=0.9, half_life=10.0)
    tmp = Path("build/.synthetic_market.csv"); tmp.parent.mkdir(parents=True, exist_ok=True)
    long.to_csv(tmp, index=False)
    o, c, d = load_market(tmp, ["V", "MA"])
    sig, _ = build_signals(c, DEFAULT)
    sl = slice(DEFAULT.formation, None)
    daily, trades = run_engine(o.iloc[sl], c.iloc[sl], d.iloc[sl], sig.iloc[sl], DEFAULT)
    reconcile(daily, trades, DEFAULT)
    picks = [trades.net_pnl.idxmin(), trades.net_pnl.idxmax()] + list(trades.index[trades.exit_reason == "max_hold"][:1])
    L = dict(c=c.iloc[sl], o=o.iloc[sl], d=d.iloc[sl], runs={"syn": dict(daily=daily)}, sig={"syn": sig.iloc[sl]})
    sess = {dd: f"Session {k + 1}" for k, dd in enumerate(c.index[sl])}
    reps = []
    for j in dict.fromkeys(picks):
        r = trades.loc[j]
        t = dict(id=f"syn-{j}", period="syn", side=int(r.side), signal_date=_d(r.signal_date), entry_date=_d(r.entry_date),
                 exit_signal_date=_d(r.exit_signal_date), exit_date=_d(r.exit_date), exit_reason=r.exit_reason, qty_v=r.qty_y, qty_ma=r.qty_x,
                 entry_px_v=r.entry_px_y, entry_px_ma=r.entry_px_x, exit_px_v=r.exit_px_y, exit_px_ma=r.exit_px_x, net_pnl=r.net_pnl,
                 equity_basis=r.equity_basis, beta=_f(r.beta), hold_sessions=int(r.hold_sessions))
        rows = replay_rows(t, L)
        for row in rows:
            row["date"] = sess[pd.Timestamp(row["date"])]
        for key in ("signal_date", "entry_date", "exit_signal_date", "exit_date"):
            t[key] = sess[pd.Timestamp(t[key])]
        t["max_hold"] = int(DEFAULT.trade_len)
        reps.append(dict(trade={k: (_f(v, 4) if isinstance(v, float) else v) for k, v in t.items()}, rows=rows))
    return dict(label="SYNTHETIC DATA: simulated prices generated by data_io.synthetic_market (seed 11) and run through the same signal and "
                      "engine code. Demonstrates the replay mechanics only; not historical evidence and not V or MA prices.",
                replays=reps)


def docs_bundle():
    root = Path("docs")
    return {name: (root / name).read_text() for name in DOCS if (root / name).exists()}


def input_checksums():
    out = {}
    for f in sorted(Path("data/raw").glob("*.csv")) + [Path("data/processed/market.csv")]:
        if f.exists():
            out[str(f)] = hashlib.sha256(f.read_bytes()).hexdigest()[:16]
    return out


# ---------------------------------------------------------------- assemble
def build(mode="local", tier="aggregate", res="results_rerun"):
    L = load(res)
    meta = dict(mode=mode, tier=tier if mode == "public" else "full", generated_utc=dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                code=code_commit(), spec_hash=DEFAULT.hash(), rf_source=L["rf_label"],
                spec=dict(formation=DEFAULT.formation, trade_len=DEFAULT.trade_len, z_lookback=DEFAULT.z_lookback, entry_z=DEFAULT.entry_z,
                          exit_z=DEFAULT.exit_z, stop_z=DEFAULT.stop_z, maxhold_mult=DEFAULT.maxhold_mult, cost_bps=DEFAULT.cost_bps,
                          borrow_bps=DEFAULT.borrow_bps, loss_limit=DEFAULT.loss_limit, dd_halt=DEFAULT.dd_halt, fill=DEFAULT.fill),
                periods={p: list(v) for p, v in PERIODS.items()})
    agg = dict(stats=sample_stats(L), execution=execution_stats(L), concentration=concentration_stats(L), earnings=earnings_stats(L),
               scenarios=scenario_records(L), docs=docs_bundle(), synthetic=synthetic_demo())
    trades = trade_table(L)
    cases = case_facts(L, trades)
    if mode == "local":
        cal = L["c"].index[L["c"].index >= pd.Timestamp(DEFAULT.dev[0])]
        z = pd.concat([L["sig"][p].z for p in PERIODS])
        eq = {p: dict(dates=[_d(x) for x in R["daily"].index], equity=[_f(v, 2) for v in R["daily"].equity],
                      drawdown=[_f(v) for v in drawdown(R["daily"].ret)]) for p, R in L["runs"].items()}
        wins = sorted({_d(w) for p in PERIODS for w in L["runs"][p]["windows"].start})
        e = L["earn"].dropna(subset=["rdq"])
        timeline = dict(dates=[_d(x) for x in cal], v=[_f(L["c"].at[x, "V"], 4) for x in cal], ma=[_f(L["c"].at[x, "MA"], 4) for x in cal],
                        z=[_f(z.get(x)) for x in cal], windows=wins, earnings=[dict(date=_d(r.rdq), ticker=r.ticker) for r in e.itertuples()],
                        equity=eq)
        replays = {t["id"]: replay_rows(t, L) for t in trades}
        meta["input_checksums"] = input_checksums()
        return dict(meta=meta, **agg, trades=trades, cases=cases, timeline=timeline, replays=replays)
    # public: construct from an allow-list
    pub_cases = dict(selection_rule=cases["selection_rule"], valuation_label=cases["valuation_label"], valuation_limits=cases["valuation_limits"], cases=[])
    narrative = ["id", "period", "depth", "role", "thesis", "decision_facts", "adjusted_ttm_eps", "valuation_reading", "scheduled_events", "catalyst",
                 "competing", "invalidating", "later", "attribution_reading", "establishes", "does_not_establish", "annotations", "side"]
    for cs in cases["cases"]:
        item = {k: cs[k] for k in narrative if k in cs}
        if tier == "derived":
            f = cs["facts"]
            item["facts"] = dict(model={k: f["model"][k] for k in ("beta", "half_life", "eg_p", "max_hold")}, valuation=dict(label=f["valuation"]["label"], v={k: f["valuation"]["v"][k] for k in ("pe", "growth", "margin", "last_report")},
                                                                  ma={k: f["valuation"]["ma"][k] for k in ("pe", "growth", "margin", "last_report")},
                                                                  **({"adjusted": {k: f["valuation"]["adjusted"][k] for k in ("v_pe", "ma_pe", "note")}} if "adjusted" in f["valuation"] else {})),
                                 outcome={k: f["outcome"][k] for k in ("exit_reason", "hold_sessions", "hold_calendar_days", "net_pnl", "pnl_pct", "v_price_pnl", "ma_price_pnl",
                                                                       "dividends", "costs", "borrow", "v_market_est", "ma_market_est", "exit_date")})
        pub_cases["cases"].append(item)
    out = dict(meta=meta, **agg, cases=pub_cases)
    if tier == "derived":
        out["trades"] = [{k: t[k] for k in ("id", "period", "side", "signal_date", "entry_date", "exit_date", "exit_reason", "hold_sessions",
                                              "hold_calendar_days", "net_pnl", "pnl_pct")} for t in trades]
        out["equity"] = {p: dict(dates=[_d(x) for x in R["daily"].index], equity=[_f(v, 2) for v in R["daily"].equity],
                                 drawdown=[_f(v) for v in drawdown(R["daily"].ret)]) for p, R in L["runs"].items()}
    return out


def case_markdown(cases):
    """docs/CASE_STUDIES.md, generated from docs/case_studies.json plus computed facts (never edit the .md by hand)."""
    def pct(x):
        return "n/a" if x is None else f"{x:+.1%}"

    def usd(x):
        return "n/a" if x is None else f"{'-' if x < 0 else '+'}${abs(x):,.0f}"
    L = [f"# Case studies\n\n*Generated by `python build_site.py --docs` from `docs/case_studies.json` and the research outputs; do not edit by hand.*\n",
         cases["selection_rule"], "", f"**Valuation figures.** {cases['valuation_label']} {cases['valuation_limits']}", ""]
    for n, cs in enumerate(cases["cases"], 1):
        f = cs["facts"]; m = f["model"]; o = f["outcome"]; v = f["valuation"]
        side = "long V / short MA" if cs["side"] == 1 else "short V / long MA"
        L += [f"## {n}. {cs['role']}: {side}, signal {cs['id']}, net {usd(o['net_pnl'])} ({o['exit_reason']})", "",
              "### Decision-time view (known at the signal close)", "",
              f"**Thesis.** {cs['thesis']}", "",
              f"**Model state.** OLS log-price hedge ratio {m['beta']:.2f}; formation half-life {m['half_life']:.1f} sessions; Engle-Granger p = {m['eg_p']:.2f} "
              f"(no evidence of cointegration at conventional levels; the hedge is an OLS fit, not an established cointegrating relation); z at the signal "
              f"{m['z_signal']:+.2f}; maximum hold {m['max_hold']} sessions. Signal day: V {pct(f['signal_day']['v'])}, MA {pct(f['signal_day']['ma'])}, "
              f"market {pct(f['signal_day']['market'])} (Fama-French).", ""]
        for x in sorted(cs.get("decision_facts", []), key=lambda x: x["date"]):
            L.append(f"- {x['date']}: {x['text']} ([{x['source']['title']}]({x['source']['url']}))")
        L += ["", f"**Valuation and operating facts** ({v['label'].rstrip('.')}). Trailing P/E on reported EPS: V {v['v']['pe']:.1f}, MA {v['ma']['pe']:.1f} "
                  f"(ratio {v['v']['pe'] / v['ma']['pe']:.2f}); trailing revenue growth V {pct(v['v']['growth'])}, MA {pct(v['ma']['growth'])}; operating margin "
                  f"V {v['v']['margin']:.1%}, MA {v['ma']['margin']:.1%}."]
        if "adjusted" in v:
            a = v["adjusted"]
            L.append(f"On company-adjusted EPS from the releases cited above: V {a['v_pe']:.1f}, MA {a['ma_pe']:.1f} (ratio {a['v_pe'] / a['ma_pe']:.2f}). {a['note']}")
        L += ["", cs["valuation_reading"], "", f"**Scheduled events.** {cs['scheduled_events']}", "",
              f"**Catalyst.** {cs['catalyst']}  **Competing explanation.** {cs['competing']}", "",
              f"**Invalidating condition.** {cs['invalidating']}", "", "### Retrospective view (outcome and later information)", ""]
        for x in cs.get("later", []):
            src = "; ".join(f"[{s['title']}]({s['url']})" for s in x["sources"])
            L.append(f"- {x['date']}: {x['text']}" + (f" ({src})" if src else ""))
        L += ["", f"**Actual leg-level P&L** (held {o['hold_sessions']} sessions, {o['hold_calendar_days']} calendar days): V price {usd(o['v_price_pnl'])}, "
                  f"MA price {usd(o['ma_price_pnl'])}, dividends {usd(o['dividends'])}, costs {usd(-o['costs'])}, borrow {usd(-o['borrow'])}, net {usd(o['net_pnl'])}. "
                  f"Estimated market contribution (past-only betas V {o['v_beta']:.2f}, MA {o['ma_beta']:.2f}; market {pct(o['market_return'])} over the hold): "
                  f"{usd(o['v_market_est'] + o['ma_market_est'])}; this is an estimate, see `diagnostics/trade_legs.py`.", "",
              cs["attribution_reading"], "", f"**What it establishes.** {cs['establishes']}", "", f"**What it does not establish.** {cs['does_not_establish']}", ""]
    L += ["## What the three cases show",
          "Winners and losers both coincided with company-specific information the model cannot read. The strategy is a statistical bet on mean "
          "reversion with no view on which dislocations are information. A fundamental filter is the obvious next idea and remains an untested "
          "hypothesis; it would need data not yet examined.", ""]
    return "\n".join(L)
